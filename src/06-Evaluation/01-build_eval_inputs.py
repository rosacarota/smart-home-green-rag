"""
01-build_eval_inputs.py
=======================
Builds the evaluation input file (eval_inputs.jsonl) by pairing each original
trigger-action rule with its RAG-generated green variant.

Output
------
data/dataset-rules/evaluation/eval_inputs.jsonl

Each line is a JSON object with the following fields:
    eval_id          : unique identifier for this evaluation pair (str)
    rule_id          : original sample_id from the dataset (str)
    original_rule    : the original IF-THEN rule text (str)
    generated_rule   : the green variant produced by the RAG pipeline (str)
    retrieved_context: the context chunks retrieved by the RAG (str | list[str])

TODO
----
Once the RAG inference script is finalised, update the two constants below:
    RAG_OUTPUT_PATH  → path to the file produced by the RAG pipeline
    load_rag_output()→ parsing logic matching the actual output format
"""

from __future__ import annotations

import json
from pathlib import Path


# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------

ROOT = Path(__file__).resolve().parents[2]

# TODO: replace with the actual path produced by the RAG inference script
RAG_OUTPUT_PATH = ROOT / "data" / "dataset-rules" / "rag_output" / "green_variants.jsonl"

OUTPUT_DIR = ROOT / "data" / "dataset-rules" / "evaluation"
OUTPUT_PATH = OUTPUT_DIR / "eval_inputs.jsonl"

# ---------------------------------------------------------------------------
# Data loading
# ---------------------------------------------------------------------------


def load_rag_output(path: Path) -> list[dict]:
    """Load the RAG-generated green variants.

    TODO: adapt this function to match the actual output format of the RAG
    pipeline once it is finalised.

    Expected keys per record (adjust as needed):
        - sample_id       : matches the original dataset id
        - original_rule   : the original IF-THEN rule
        - generated_rule  : the green variant generated by the RAG
        - retrieved_context: retrieved passages (string or list of strings)

    Returns
    -------
    list[dict]
        One dict per rule pair.
    """
    if not path.exists():
        raise FileNotFoundError(
            f"RAG output file not found: {path}\n"
            "Run the RAG inference script first, then update RAG_OUTPUT_PATH."
        )

    records: list[dict] = []

    # TODO: update suffix/parser if the RAG outputs .json instead of .jsonl
    suffix = path.suffix.lower()
    if suffix == ".jsonl":
        with path.open(encoding="utf-8") as f:
            for lineno, line in enumerate(f, start=1):
                line = line.strip()
                if not line:
                    continue
                try:
                    records.append(json.loads(line))
                except json.JSONDecodeError as exc:
                    raise ValueError(
                        f"Invalid JSON on line {lineno} of {path}: {exc}"
                    ) from exc
    elif suffix == ".json":
        raw = json.loads(path.read_text(encoding="utf-8"))
        # TODO: adjust key name if the top-level wrapper uses a different key
        records = raw if isinstance(raw, list) else raw.get("rows", raw.get("results", []))
    else:
        raise ValueError(f"Unsupported RAG output format: {suffix}")

    return records


def validate_record(record: dict, index: int) -> None:
    """Raise ValueError if a required field is missing or empty."""
    # TODO: extend this list once the final RAG output schema is known
    required_fields = ["sample_id", "original_rule", "generated_rule"]
    for field in required_fields:
        if field not in record:
            raise ValueError(
                f"Record {index} is missing required field '{field}': {record}"
            )
        if not str(record[field]).strip():
            raise ValueError(
                f"Record {index} has empty field '{field}': {record}"
            )


# ---------------------------------------------------------------------------
# Building eval inputs
# ---------------------------------------------------------------------------


def build_eval_inputs(records: list[dict]) -> list[dict]:
    """Convert raw RAG output records into the standard evaluation input format.

    Parameters
    ----------
    records:
        Parsed records from the RAG output file.

    Returns
    -------
    list[dict]
        Evaluation input records ready to be written to eval_inputs.jsonl.
    """
    eval_inputs: list[dict] = []

    for i, record in enumerate(records):
        validate_record(record, index=i)

        # TODO: adjust field names to match the actual RAG output schema
        rule_id: str = str(record["sample_id"])
        original_rule: str = str(record["original_rule"]).strip()
        generated_rule: str = str(record["generated_rule"]).strip()

        # retrieved_context may be a string or a list of strings
        # TODO: confirm the shape of this field in the RAG output
        retrieved_context = record.get("retrieved_context", "")
        if isinstance(retrieved_context, list):
            retrieved_context = "\n\n".join(str(c) for c in retrieved_context)

        eval_inputs.append(
            {
                "eval_id": f"EVAL_{rule_id}",
                "rule_id": rule_id,
                "original_rule": original_rule,
                "generated_rule": generated_rule,
                "retrieved_context": retrieved_context,
            }
        )

    return eval_inputs


# ---------------------------------------------------------------------------
# I/O
# ---------------------------------------------------------------------------


def write_eval_inputs(eval_inputs: list[dict], output_path: Path) -> None:
    output_path.parent.mkdir(parents=True, exist_ok=True)

    with output_path.open("w", encoding="utf-8") as f:
        for record in eval_inputs:
            f.write(json.dumps(record, ensure_ascii=False) + "\n")

    print(f"Wrote {len(eval_inputs)} eval inputs → {output_path}")


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------


def main() -> None:
    print(f"Loading RAG output from: {RAG_OUTPUT_PATH}")
    records = load_rag_output(RAG_OUTPUT_PATH)
    print(f"  Loaded {len(records)} records.")

    eval_inputs = build_eval_inputs(records)
    print(f"  Built {len(eval_inputs)} evaluation pairs.")

    write_eval_inputs(eval_inputs, OUTPUT_PATH)
    print("Done.")


if __name__ == "__main__":
    main()
